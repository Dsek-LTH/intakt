package zettle

import "encoding/json"

type PurchaseDiscount struct {
	Name       string   `json:"name"`
	Percentage *float64 `json:"percentage,omitempty"`
	Amount     *int     `json:"amount,omitempty"`
	Quantity   int      `json:"quantity"`
	Value      int      `json:"value"`
}

type ProductDiscount struct {
	Percentage *float64 `json:"percentage,omitempty"`
	Amount     *int     `json:"amount,omitempty"`
	Quantity   int      `json:"quantity"`
}

type Payment struct {
	UUID       string `json:"uuid"`
	Amount     int    `json:"amount"`
	Type       string `json:"type"`
	Attributes struct {
	} `json:"attributes"`
}

type ServiceCharge struct {
	Amount        int     `json:"amount"`
	Title         string  `json:"title"`
	VatPercentage float64 `json:"vatPercentage"`
	Quantity      string  `json:"quantity"`
}

type GPSCoordinates struct {
	Longitude      float64 `json:"longitude"`
	Latitude       float64 `json:"latitude"`
	AccuracyMeters float64 `json:"accuracyMeters"`
}

type Product struct {
	Quantity         string  `json:"quantity"`
	ProductUUID      string  `json:"productUuid"`
	VariantUUID      string  `json:"variantUuid"`
	VatPercentage    float64 `json:"vatPercentage"`
	UnitPrice        int     `json:"unitPrice"`
	RowTaxableAmount int     `json:"rowTaxableAmount"`

	Name        string `json:"name"`
	Description string `json:"description,omitempty"`
	VariantName string `json:"variantName"`

	Discount      *ProductDiscount `json:"discount,omitempty"`
	DiscountValue int              `json:"discountValue,omitempty"`
	Comment       string           `json:"comment,omitempty"`

	FromLocationUUID string `json:"fromLocationUuid,omitempty"`
	ToLocationUUID   string `json:"toLocationUuid,omitempty"`

	AutoGenerated  bool   `json:"autoGenerated,omitempty"`
	ID             string `json:"id,omitempty"`
	Type           string `json:"type"`
	LibraryProduct bool   `json:"libraryProduct"`
}

type Purchase struct {
	Source               string `json:"source"`
	PurchaseUUID         string `json:"purchaseUUID"`
	PurchaseUUID1        string `json:"purchaseUUID1"`
	Timestamp            string `json:"timestamp"`
	PurchaseNumber       int    `json:"purchaseNumber"`
	GlobalPurchaseNumber int    `json:"globalPurchaseNumber"`

	Amount    int    `json:"amount"`
	VatAmount int    `json:"vatAmount"`
	Country   string `json:"country"`
	Currency  string `json:"currency"`

	ReturnExchangePurchaseUUID *string `json:"returnExchangePurchaseUuid,omitempty"`
	SaleExchangePurchaseUUID   *string `json:"saleExchangePurchaseUuid,omitempty"`
	ExchangeType               *string `json:"exchangeType,omitempty"`

	Products []Product `json:"products"`
	Payments []Payment `json:"payments"`

	Discounts []PurchaseDiscount `json:"discounts,omitempty"`

	ServiceCharge *ServiceCharge `json:"serviceCharge,omitempty"`

	Created string `json:"created"`

	Refund   bool `json:"refund"`
	Refunded bool `json:"refunded"`

	RefundsPurchaseUUID  *string `json:"refundsPurchaseUUID,omitempty"`
	RefundsPurchaseUUID1 *string `json:"refundsPurchaseUUID1,omitempty"`

	RefundedByPurchaseUUIDs  []string `json:"refundedByPurchaseUUIDs,omitempty"`
	RefundedByPurchaseUUIDs1 []string `json:"refundedByPurchaseUUIDs1,omitempty"`

	GroupedVatAmounts map[string]int `json:"groupedVatAmounts,omitempty"`

	UserDisplayName string          `json:"userDisplayName"`
	GpsCoordinates  *GPSCoordinates `json:"gpsCoordinates,omitempty"`

	// Zettle says this is internal. Use RawMessage unless you know its exact schema.
	CashRegister json.RawMessage `json:"cashRegister,omitempty"`

	CustomAmountSale bool `json:"customAmountSale"`
}

type purchasePage struct {
	Purchases         []Purchase `json:"purchases"`
	FirstPurchaseHash string     `json:"firstPurchaseHash"`
	LastPurchaseHash  string     `json:"lastPurchaseHash"`
	LinkUrls          []string   `json:"linkUrls"`
}

type TransactionFee struct {
	Timestamp                  string `json:"timestamp"`
	Amount                     int    `json:"amount"`
	OriginatorTransactionType  string `json:"originatorTransactionType"`
	OriginatingTransactionUUID string `json:"originatingTransactionUuid"`
}
